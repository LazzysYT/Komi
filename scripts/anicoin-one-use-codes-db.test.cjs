async function as(db,role,sub='',jwt={}){
 assert.ok(['anon','authenticated','service_role'].includes(role));
 await db.exec('reset role');
 await db.query("select set_config('request.jwt.claim.sub',$1,false),set_config('request.jwt.claims',$2,false)",[sub,JSON.stringify(jwt)]);
 await db.exec('set role '+role);
}
const rpc=async(db,name,args=[])=>(await db.query('select public.komi_'+name+'('+args.map((_,i)=>'$'+(i+1)).join(',')+') as v',args)).rows[0].v;
const issue=(db,n)=>rpc(db,'admin_anicoin_code_create',[n]);
const list=(db)=>rpc(db,'admin_anicoin_code_list');
const revoke=(db,id)=>rpc(db,'admin_anicoin_code_revoke',[id]);
const redeem=(db,code)=>rpc(db,'redeem_anicoin_code',[code]);
const wallets=(db)=>db.query('select user_id,balance,watch_seconds from public.komi_anicoin_wallets order by user_id').then(r=>r.rows);
const credits=(db)=>db.query("select user_id,delta,reason from public.komi_anicoin_ledger where reason='promo_anicoin_code' order by id").then(r=>r.rows);

localTest('admin-only issuance is bounded, checkout-independent, and stores only digest and non-sensitive hint',async(t)=>{
 const db=await fixture();t.after(()=>db.close());
 await as(db,'authenticated',admin);
 assert.deepEqual(await list(db),[]);
 for(const n of [null,0,-1,10001]) await assert.rejects(issue(db,n),{code:'22023'});
 const a=await issue(db,1),b=await issue(db,10000);
 assert.deepEqual(Object.keys(a).sort(),['amount','code','id','status']);
 assert.equal(a.status,'active');assert.equal(a.amount,1);assert.equal(b.amount,10000);
 assert.match(a.code,shape);assert.match(b.code,shape);assert.notEqual(a.code,b.code);assert.notEqual(a.id,b.id);
 const entries=await list(db);assert.equal(entries.length,2);
 for(const item of entries){
  assert.deepEqual(Object.keys(item).sort(),['amount','created_at','hint','id','redeemed_at','status']);
  assert.equal(item.redeemed_at,null);assert.equal(item.status,'active');assert.match(item.hint,/^…[0-9A-F]{4}$/);
 }
 assert.equal(entries.find(x=>x.id===a.id).hint,'…'+a.code.slice(-4));
 assert.equal(JSON.stringify(entries).includes(a.code),false);
 await assert.rejects(db.query('select * from komi_anicoin_code_private.codes'),forbidden);
 await db.exec('reset role');
 const stored=(await db.query("select encode(code_sha256,'hex') as digest, hint, created_by from komi_anicoin_code_private.codes where id=$1",[a.id])).rows[0];
 assert.deepEqual(stored,{digest:createHash('sha256').update(a.code).digest('hex'),hint:'…'+a.code.slice(-4),created_by:admin});
 const columnNames=(await db.query("select column_name from information_schema.columns where table_schema='komi_anicoin_code_private' and table_name='codes'")).rows.map(x=>x.column_name);
 assert.equal(columnNames.includes('code'),false);
 assert.equal((await db.query("select relrowsecurity from pg_class where oid='komi_anicoin_code_private.codes'::regclass")).rows[0].relrowsecurity,true);
 assert.deepEqual((await db.query('select code,uses_count from public.promo_codes')).rows,[{code:'PREMIUM_TEST_ONLY',uses_count:0}]);
 await assert.rejects(db.query("insert into public.promo_codes(code) values($1)",[a.code]),{code:'23514'});
 await as(db,'authenticated',alice,{user_metadata:{role:'admin'},app_metadata:{role:'admin'}});
 await assert.rejects(issue(db,1),forbidden);await assert.rejects(list(db),forbidden);await assert.rejects(revoke(db,a.id),forbidden);
 for(const [account,jwt] of [[anonAccount,{}],[deleted,{}],[absent,{}],['',{}],[admin,{is_anonymous:true}]]){
  await as(db,'authenticated',account,jwt);
  await assert.rejects(issue(db,1),forbidden);await assert.rejects(list(db),forbidden);await assert.rejects(redeem(db,a.code),forbidden);
 }
 for(const role of ['anon','service_role']){
  await as(db,role,admin);
  await assert.rejects(issue(db,1),forbidden);await assert.rejects(list(db),forbidden);await assert.rejects(revoke(db,a.id),forbidden);
  await assert.rejects(redeem(db,a.code),forbidden);
 }
});

localTest('one recipient globally, exact credit, retry returns current balance, no consumer data leaks, no reuse after deletion',async(t)=>{
 const db=await fixture();t.after(()=>db.close());
 await as(db,'authenticated',admin);const a=await issue(db,35),b=await issue(db,7);
 await as(db,'authenticated',alice);
 assert.deepEqual(await redeem(db,' \t'+a.code.toLowerCase()+'\n'),{status:'redeemed',amount:35,balance:55});
 assert.deepEqual(await redeem(db,a.code),{status:'already_redeemed',amount:35,balance:55});
 await db.exec('reset role');
 await db.query('update public.komi_anicoin_wallets set balance=balance-13 where user_id=$1',[alice]);
 await as(db,'authenticated',alice);
 assert.deepEqual(await redeem(db,a.code),{status:'already_redeemed',amount:35,balance:42});
 await as(db,'authenticated',bob);
 const unknown="KOMI-AC-00000000-00000000-00000000-00000000";
 assert.deepEqual(await redeem(db,a.code),genericUnavailable);
 assert.deepEqual(await redeem(db,unknown),genericUnavailable);
 for(const invalid of [null,'',' '.repeat(81),'KOMI-AC-…','PREMIUM_TEST_ONLY',a.code+'X'])
  assert.deepEqual(await redeem(db,invalid),{status:'invalid'});
 assert.deepEqual(await redeem(db,b.code),{status:'redeemed',amount:7,balance:7});
 await as(db,'authenticated',admin);
 const read=await list(db);
 assert.deepEqual(read.map(x=>x.status),['redeemed','redeemed']);
 assert.ok(read.every(x=>typeof x.redeemed_at==='string'));
 assert.equal(JSON.stringify(read).includes(alice),false);assert.equal(JSON.stringify(read).includes(a.code),false);
 assert.deepEqual(await revoke(db,a.id),{status:'redeemed'});
 await db.exec('reset role');
 assert.deepEqual(await wallets(db),[{user_id:alice,balance:42,watch_seconds:420},{user_id:bob,balance:7,watch_seconds:0}]);
 assert.deepEqual(await credits(db),[{user_id:alice,delta:35,reason:'promo_anicoin_code'},{user_id:bob,delta:7,reason:'promo_anicoin_code'}]);
 assert.deepEqual((await db.query("select reason from public.komi_anicoin_ledger where reason<>'promo_anicoin_code' order by id")).rows.map(x=>x.reason),legacyReasons);
 assert.deepEqual((await db.query("select convalidated from pg_constraint where conrelid='public.komi_anicoin_ledger'::regclass and conname='komi_anicoin_ledger_reason_check'")).rows,[{convalidated:false}]);
 await assert.rejects(db.query("insert into public.komi_anicoin_ledger(user_id,delta,reason) values($1,1,'incorrect')",[alice]),{code:'23514'});
 await db.query('delete from auth.users where id=$1',[alice]);
 await as(db,'authenticated',bob);
 assert.deepEqual(await redeem(db,a.code),genericUnavailable);
 await as(db,'authenticated',admin);
 assert.equal((await list(db)).find(x=>x.id===a.id).status,'redeemed');
});

localTest('revocation wins if first, ledger failure rolls back consumption and balance, ledger validation state preserved',async(t)=>{
 const db=await fixture({ledgerValidated:true});t.after(()=>db.close());
 await as(db,'authenticated',admin);
 const a=await issue(db,12),b=await issue(db,50);
 assert.deepEqual(await revoke(db,a.id),{status:'revoked'});
 assert.deepEqual(await revoke(db,a.id),{status:'revoked'});
 assert.deepEqual(await revoke(db,uuid(900)),genericUnavailable);
 await as(db,'authenticated',alice);
 assert.deepEqual(await redeem(db,a.code),genericUnavailable);
 await db.exec('reset role');
 await db.exec("alter table public.komi_anicoin_ledger add constraint force_test_rollback check(reason<>'promo_anicoin_code')");
 await as(db,'authenticated',alice);
 await assert.rejects(redeem(db,b.code),{code:'23514'});
 await db.exec('reset role');
 assert.deepEqual(await credits(db),[]);
 assert.deepEqual(await wallets(db),[{user_id:alice,balance:20,watch_seconds:420}]);
 await db.exec("alter table public.komi_anicoin_ledger drop constraint force_test_rollback");
 await as(db,'authenticated',admin);
 assert.deepEqual((await list(db)).map(x=>x.status),['active','revoked']);
 await as(db,'authenticated',bob);
 assert.deepEqual(await redeem(db,b.code),{status:'redeemed',amount:50,balance:50});
 await db.exec('reset role');
 assert.deepEqual((await db.query("select convalidated from pg_constraint where conrelid='public.komi_anicoin_ledger'::regclass and conname='komi_anicoin_ledger_reason_check'")).rows,[{convalidated:true}]);
 assert.deepEqual(await credits(db),[{user_id:bob,delta:50,reason:'promo_anicoin_code'}]);
});
