'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const read = file => fs.readFileSync(path.join(__dirname,'..',file),'utf8');
const app = read('app-main.js'), art = read('hero-hd-art.js'), home=read('home-discovery.js'), css=read('komi-hero-senku.css'), admin=read('komi-admin-ui.js');
for(const code of [app,art,home,admin]) new vm.Script(code);
assert.match(app,/description:data->>desc,still:data->screenshots->>0/);
assert.match(app,/banner_url:bannerUrl,banner_video_url:videoUrl/);
assert.match(admin,/animeHeroBanner/);
assert.match(admin,/animeHeroVideo/);
assert.match(home,/data-komi-hero-video/);
assert.match(art,/video\.muted = true/);
assert.match(art,/video\.play\(\)\.catch/);
assert.match(art,/description\.textContent = item\.description/);
assert.match(css,/object-fit:contain !important/);
assert.match(css,/--komi-hero-progress/);
assert.match(css,/prefers-reduced-motion:reduce/);
const start=app.indexOf('function startHeroAutoSlide()');
const end=app.indexOf('function changeSlide(direction)',start);
let now=0,tick,changes=0,progress='0%',paused=false;
const slider={isConnected:true,style:{setProperty:(key,value)=>{if(key==='--komi-hero-progress')progress=value;}},matches:()=>paused,querySelectorAll:()=>[{},{}],querySelector:()=>({complete:true,naturalWidth:1920})};
const context=vm.createContext({document:{getElementById:()=>slider,hidden:false,readyState:'complete'},window:{matchMedia:()=>({matches:false})},navigator:{},komiHomeCatalogReady:true,slideInterval:null,currentSlideIndex:0,performance:{now:()=>now},setInterval:cb=>(tick=cb,1),clearInterval:()=>{},updateHeroSlideView:()=>changes++});
vm.runInContext(app.slice(start,end)+'\nstartHeroAutoSlide();',context);
const advance=n=>{for(let i=0;i<n;i++){now+=100;tick();}};
advance(50);assert.equal(progress,'50.0%');assert.equal(changes,0);
paused=true;advance(50);assert.equal(progress,'50.0%');assert.equal(changes,0);
paused=false;advance(50);assert.equal(progress,'0%');assert.equal(changes,1);
console.log('V8.11 hero contracts and pause/resume progress verified');
